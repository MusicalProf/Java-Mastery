package Exercises.VariablesPractice;

public class AssignTwoFloatingPoint {
    public static void main(String[] args) {
        // Assign two floating-point values and print their sum.
        float x = 3.5f;
        float y = 4.6f;
        float sum = x + y;

        System.out.println("Sum of floats: " + sum);
    }
}
