package Exercises.VariablesPractice;

public class IntializeAndPrintStringArray {
    public static void main(String[] args) {
        // Initialize a string array and print its elements
        String[] fruits = {"Grapes", "Kiwis", "Apples", "Watermelons", "Oranges", "Strawberries"};
        System.out.println("Favorite Fruits:");
        System.out.println(fruits[0]);
        System.out.println(fruits[1]);
        System.out.println(fruits[2]);
        System.out.println(fruits[3]);
        System.out.println(fruits[4]);
        System.out.println(fruits[5]);
    }
}
